"""Write docs/CONVERSATION_VOCABULARY.md from backend/config/conversation_vocabulary.json, the model's labels, the clips on disk and the text to gloss.
usage (repository root):  backend\\.venv\\Scripts\\python tools\\conversation_report.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

import spacy  # noqa: E402

from app.conversation_vocab import load_vocabulary  # noqa: E402
from nlp.lexicon import load_lexicon  # noqa: E402
from nlp.text_to_gloss import text_to_gloss  # noqa: E402

TAKES = 8  # guided session default, TRAINING_PLAN_SELF_RECORDED.md section 8
v = load_vocabulary()
classes = json.loads((ROOT / "backend" / "models" / "labels.json").read_text(encoding="utf-8"))["classes"]
clips = {p.stem.upper() for p in (ROOT / "frontend" / "public" / "animations").glob("*.json") if p.stem != "index"}
lex = load_lexicon()
nlp = spacy.load("en_core_web_sm")
todo = set(v.to_record())
n_rec, n_known = len(v.to_record()), len(v.known())

o: list[str] = []
P = o.append
P("# Conversation vocabulary\n")
P(f"{len(v.signs)} signs for basic dialogue. **{n_known} already exist as INCLUDE classes** (the live model can recognize them) and **{n_rec} must be recorded**. "
  "Generated by `tools/conversation_report.py` from `backend/config/conversation_vocabulary.json`, the model's `labels.json` and the clips on disk. "
  "No sign here is signer reviewed.\n")
P("## What to record\n")
P(f"- Signs to record: **{n_rec}**.")
P(f"- Takes: the guided session default is {TAKES} takes per sign per signer, so **{n_rec} x {TAKES} = {n_rec * TAKES} accepted takes per signer**.")
P(f"- For the plan in `docs/TRAINING_PLAN_SELF_RECORDED.md` (signer roles S01 to S05, 5 signers): {n_rec} x {TAKES} x 5 = **{n_rec * TAKES * 5} takes**. "
  f"Smoke test (2 signers, 5 takes): {n_rec * 5 * 2}. Recommended level (8 signers, 10 takes): {n_rec * 10 * 8}.")
P(f"- Optional, to measure the webcam domain shift of the {n_known} known signs: 5 takes each per signer = {n_known * 5} more takes per signer.")
P("- Rejected takes do not count; plan for about 20 percent retries (see the training plan).")
P("- Record them in the Record sign tab, Guided session, preset **Conversation vocabulary** (lists only the signs to record).\n")
P("## Vocabulary\n")
P("| Group | Gloss | Status | INCLUDE class | Clip now | In gloss dictionary | Note |")
P("|---|---|---|---|---|---|---|")
for s in v.signs:
    status = "record" if s.must_record else "in INCLUDE"
    inc = s.include_class or ""
    if s.include_class is not None:
        assert s.include_class in classes, s.include_class
    P(f"| {s.group} | {s.gloss} | {status} | {inc} | {'yes' if s.gloss in clips else 'no'} | {'yes' if s.gloss in lex.signs else 'no'} | {s.note} |")
P("\nA sign marked INCLUDE is a class of the INCLUDE dataset, so the model can output it and a clip (an unreviewed retarget of one INCLUDE sample) exists. "
  "A sign marked record has neither a class nor a clip. Results for these signs on the authors' predefined split, signer independence not verified.\n")
P("## Test sentences\n")
P("Gloss from the rule based text to gloss; \"Missing\" are the signs without a clip on disk. A word that is not in the gloss dictionary is fingerspelled (FS:), "
  "and fingerspelling clips do not exist, so it is missing too.\n")
P("| # | Sentence | Gloss | Missing (no clip) | Missing, still to record |")
P("|---|---|---|---|---|")
for i, text in enumerate(v.test_sentences, 1):
    r = text_to_gloss(text, nlp, lex)
    miss = [t.gloss for t in r.tokens if (t.gloss not in clips)]
    rec = [m for m in miss if m.replace("FS:", "") in todo]
    P(f"| {i} | {text} | {' '.join(r.gloss)} | {', '.join(miss) or 'none'} | {', '.join(rec) or 'none'} |")
out = ROOT / "docs" / "CONVERSATION_VOCABULARY.md"
out.write_text("\n".join(o) + "\n", encoding="utf-8", newline="\n")
print("\n".join(o[:12]))
print(out)
